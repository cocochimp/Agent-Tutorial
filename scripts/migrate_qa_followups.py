def extract_qa_block(html):
    """定位 <h3>…面试追问…</h3><div class="qa">…配对闭合…</div>，返回 (details_pairs, cleaned_html)。"""
    i = html.find('面试追问')
    if i < 0:
        return [], html
    h3 = html.rfind('<h3', 0, i)
    if h3 < 0:
        return [], html
    h3end = html.find('</h3>', h3)
    if h3end < 0:
        return [], html
    qa_start = html.find('<div class="qa">', h3end)
    if qa_start < 0:
        return [], html
    depth = 1
    pos = qa_start + len('<div class="qa">')
    while pos < len(html) and depth > 0:
        nxt_open = html.find('<div', pos)
        nxt_close = html.find('</div>', pos)
        if nxt_close < 0:
            break
        if nxt_open >= 0 and nxt_open < nxt_close:
            depth += 1
            pos = nxt_open + 5
        else:
            depth -= 1
            pos = nxt_close + 6
    qa_end = pos
    block = html[h3:qa_end]
    pairs = re.findall(
        r'<details[^>]*>\s*<summary>(.*?)</summary>\s*<div class="answer">(.*?)</div>\s*</details>',
        block, re.S)
    cleaned = html[:h3] + html[qa_end:]
    cleaned = re.sub(r'\n{3,}', '\n\n', cleaned)
    return pairs, cleaned


def split_sentences(text):
    return [s.strip() for s in re.split(r'[。；!？\n]', text) if len(s.strip()) >= 8]


def make_points(answer, n=3, cap=46):
    """从答案提炼要点（分句取最长几句截断）。"""
    sents = sorted(split_sentences(re.sub(r'<[^>]+>', '', answer)), key=len, reverse=True)
    pts = []
    for s in sents:
        s = s.replace('“', '').replace('”', '').strip()
        if s in pts:
            continue
        pts.append(s[:cap] + ('…' if len(s) > cap else ''))
        if len(pts) >= n:
            break
    return pts


