def patch_answer(a, extra):
    # 追加到第 4 段「我的动作」末尾
    segs = a.split('\n')
    out = []
    for s in segs:
        out.append(s)
        if s.startswith('4. 我的动作'):
            out.append('（补充）' + extra)
    return '\n'.join(out)

